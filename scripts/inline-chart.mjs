/**
 * 把 Chart.js 的 UMD 构建内联进 client/client.js。
 *
 * 为什么内联：插件面板的客户端文件由 DSH 在页面加载时从磁盘读取，
 * 而 host 的路由表只在启动时注册。之前把库放在 /asset/chart.js 这类
 * 独立路由上，出现「客户端已是新版、host 还是旧路由」→ 404 → 图表降级。
 * 内联之后库跟着客户端一起走，刷新页面即可生效，不依赖新增路由。
 *
 *   node scripts/inline-chart.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { createRequire } from 'node:module'

const require = createRequire(import.meta.url)
const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, '..')
const chartUmd = readFileSync(join(dirname(require.resolve('chart.js')), 'chart.umd.js'), 'utf8')

const START = '  // >>> chart.js (generated by scripts/inline-chart.mjs) >>>'
const END = '  // <<< chart.js <<<'

const block = [
  START,
  '  // Chart.js 4 (MIT)。UMD 包在局部 module/exports 里，不会污染插件的模块对象。',
  '  var ChartLib = (function () {',
  '    var module = { exports: {} }',
  '    var exports = module.exports',
  chartUmd
    .split('\n')
    .map((line) => (line ? '    ' + line : line))
    .join('\n'),
  '    return module.exports',
  '  })()',
  END,
].join('\n')

const target = join(root, 'client', 'client.js')
let source = readFileSync(target, 'utf8')
const startIndex = source.indexOf(START)
const endIndex = source.indexOf(END)

if (startIndex >= 0 && endIndex > startIndex) {
  source = source.slice(0, startIndex) + block + source.slice(endIndex + END.length)
} else {
  // 第一次插入：放在 factory 顶部（exports 声明之后）
  const anchor = '  var module = { exports: {} };\n'
  if (!source.includes(anchor)) throw new Error('client.js 结构变了，找不到插入点')
  source = source.replace(anchor, anchor + block + '\n')
}

writeFileSync(target, source, 'utf8')
const kb = Math.round(Buffer.byteLength(source) / 1024)
console.log(`内联完成：client/client.js → ${kb} KB`)
