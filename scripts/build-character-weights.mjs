const out = {}
for (const line of TABLE.split('\n')) {
  const trimmed = line.trim()
  if (!trimmed) continue
  const parts = trimmed.split(/\s+/)
  const name = parts[0]
  const numbers = parts.slice(1).map(Number)
  if (numbers.length !== 7 || numbers.some((value) => !Number.isFinite(value))) {
    throw new Error('bad row: ' + trimmed)
  }
  const [hp, atk, def, critRate, critDMG, em, er] = numbers
  out[name] = { hp: hp / 100, atk: atk / 100, def: def / 100, critRate: critRate / 100, critDMG: critDMG / 100, em: em / 100, er: er / 100 }
}

